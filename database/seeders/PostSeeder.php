    /**
     * Seed the demo blog posts.
     */
    public function run(): void
    {
        if (Post::query()->exists()) {
            return;
        }

        $tagIds = Tag::pluck('id', 'name');
        $now = now();

        foreach ($this->posts() as $data) {
            $post = Post::create([
                'title' => $data['title'],
                'body' => $data['body'],
                'is_visible' => $data['visible'],
            ]);

            $createdAt = $now->copy()->subDays($data['days_ago'])->setTime(9, 0);

            $post->forceFill([
                'created_at' => $createdAt,
                'updated_at' => $createdAt,
            ])->saveQuietly();

            $post->tags()->sync(
                collect($data['tags'])
                    ->map(fn (string $name): int => $tagIds[$name])
                    ->all(),
            );
        }

    }

